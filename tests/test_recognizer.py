"""Тесты чистой логики распознавания: склейка кусков длинной записи."""
import pytest

from voicetocode.recognizer import _join_parts


@pytest.mark.parametrize(
    "parts, expected",
    [
        # обычная склейка: оба куска - самостоятельные предложения
        (["Привет.", "Как дела?"], "Привет. Как дела?"),
        # кусок продолжает предложение - точка на стыке лишняя
        (["Мне нужно посмотреть.", "как работает модуль."], "Мне нужно посмотреть как работает модуль."),
        # лишние пробелы и пустые куски не должны попасть в текст
        (["  Первый.  ", "", "   ", "Второй."], "Первый. Второй."),
        ([], ""),
        (["Один."], "Один."),
    ],
)
def test_join_parts(parts, expected):
    assert _join_parts(parts) == expected
